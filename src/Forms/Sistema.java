    private void aplicarEfectoHover(javax.swing.JButton btn) {
        java.awt.Color colorOriginal = new java.awt.Color(40, 40, 40);
        java.awt.Color colorHover = new java.awt.Color(90, 90, 90);
        java.awt.Font fuenteOriginal = new java.awt.Font("Roboto Black", java.awt.Font.BOLD, 19);
        java.awt.Font fuenteZoom = new java.awt.Font("Roboto Black", java.awt.Font.BOLD, 22);
        btn.setBackground(colorOriginal);
        btn.setForeground(java.awt.Color.WHITE);
        btn.setOpaque(true);
        btn.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseEntered(java.awt.event.MouseEvent evt) {
                btn.setBackground(colorHover);
                btn.setFont(fuenteZoom);
                btn.setCursor(new java.awt.Cursor(java.awt.Cursor.HAND_CURSOR));
            }

            @Override
            public void mouseExited(java.awt.event.MouseEvent evt) {
                btn.setBackground(colorOriginal);
                btn.setFont(fuenteOriginal);
            }
        });
    }

