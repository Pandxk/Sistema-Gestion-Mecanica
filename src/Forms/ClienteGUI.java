    public void ListarClientes() {
        model = (DefaultTableModel) tablaListado.getModel();
        model.setRowCount(0);
        List<Cliente> lista = cliControl.findClienteEntities();
        Object[] ob = new Object[5];
        for (Cliente c : lista) {
            ob[0] = c.getIdCliente();
            ob[1] = c.getCedula();
            ob[2] = c.getNombre();
            ob[3] = c.getDireccion();
            ob[4] = c.getTelefono();
            model.addRow(ob);
        }
        tablaListado.setModel(model);
    }

