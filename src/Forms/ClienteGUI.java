    private void btn_modActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_modActionPerformed
        int fila = tablaListado.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(null, "POR FAVOR SELECCIONE, UN CLIENTE.");
            return;
        }
        int idCliente = Integer.parseInt(tablaListado.getValueAt(fila, 0).toString());
        JFrame framePadre = (JFrame) SwingUtilities.getWindowAncestor(this);
        JPanel fondoOscuro = new JPanel() {
            @Override
            protected void paintComponent(Graphics g) {
                g.setColor(new Color(0, 0, 0, 150));
                g.fillRect(0, 0, getWidth(), getHeight());
            }
        };
        fondoOscuro.setOpaque(false);
        framePadre.setGlassPane(fondoOscuro);
        fondoOscuro.setVisible(true);
        Forms.FormularioCliente ventana = new Forms.FormularioCliente(framePadre, true, this, idCliente);
        ventana.setVisible(true);
        fondoOscuro.setVisible(false);
    }//GEN-LAST:event_btn_modActionPerformed

