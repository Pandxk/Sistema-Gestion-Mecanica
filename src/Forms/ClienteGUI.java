    private void btn_elim1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_elim1ActionPerformed
        int fila = tablaListado.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(null, "SELECCIONE UN CLIENTE PARA ELIMINAR");
            return;
        }
        int confirmacion = JOptionPane.showConfirmDialog(null,
                "¿Está seguro de eliminar este cliente? Se borrarán sus vehículos asociados.",
                "Confirmar Eliminación",
                JOptionPane.YES_NO_OPTION);
        if (confirmacion == JOptionPane.YES_OPTION) {
            try {
                int idCliente = Integer.parseInt(tablaListado.getValueAt(fila, 0).toString());
                cliControl.destroy(idCliente);
                JOptionPane.showMessageDialog(null, "CLIENTE ELIMINADO");
                ListarClientes();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "ERROR AL ELIMINAR" + e.getMessage());
            }
        }
    }//GEN-LAST:event_btn_elim1ActionPerformed

