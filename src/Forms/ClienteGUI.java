    private void btn_buscar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_buscar1ActionPerformed
        int criterio = cbx_criterio.getSelectedIndex();
        String texto = txt_buscar.getText().trim().toUpperCase();
        if (criterio == 0) {
            JOptionPane.showMessageDialog(null, "Por favor, seleccione buscar por PLACA o MARCA.");
            return;
        }
        if (texto.isEmpty()) {
            ListarClientes();
            return;
        }
        model = (DefaultTableModel) tablaListado.getModel();
        model.setRowCount(0);

        List<Cliente> lista = cliControl.findClienteEntities();
        boolean encontrado = false;
        Object[] ob = new Object[5];

        for (Cliente c : lista) {
            boolean coincide = false;

            if (criterio == 1) {
                if (c.getCedula() != null && c.getCedula().startsWith(texto)) {
                    coincide = true;
                }
            } else if (criterio == 2) {
                if (c.getNombre() != null && c.getNombre().toUpperCase().contains(texto)) {
                    coincide = true;
                }
            }

            if (coincide) {
                ob[0] = c.getIdCliente();
                ob[1] = c.getCedula();
                ob[2] = c.getNombre();
                ob[3] = c.getDireccion();
                ob[4] = c.getTelefono();
                model.addRow(ob);
                encontrado = true;
            }
        }
        if (!encontrado) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontraron clientes con ese dato.");
            ListarClientes();
        }
    }//GEN-LAST:event_btn_buscar1ActionPerformed

