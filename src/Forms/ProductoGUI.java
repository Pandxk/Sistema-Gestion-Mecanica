    public void ListarProductos() {
        emf.getCache().evictAll();
        model = (DefaultTableModel) tablaListado.getModel();
        model.setRowCount(0);
        List<Producto> lista = prodControl.findProductoEntities();
        Object[] ob = new Object[6];
        for (Producto p : lista) {
            ob[0] = p.getIdProducto();
            ob[1] = p.getCodigo();
            ob[2] = p.getNombre();
            ob[3] = p.getMarca();
            ob[4] = p.getStock();
            ob[5] = String.format("$ %.2f", p.getPrecio());
            model.addRow(ob);
        }
        tablaListado.setModel(model);
    }

    public void seleccionarProductoNuevo(int idNuevo) {
        for (int i = 0; i < tablaListado.getRowCount(); i++) {
            int idFila = Integer.parseInt(tablaListado.getValueAt(i, 0).toString());
            if (idFila == idNuevo) {
                tablaListado.setRowSelectionInterval(i, i);
                tablaListado.scrollRectToVisible(tablaListado.getCellRect(i, 0, true));
                break;
            }
        }
    }

