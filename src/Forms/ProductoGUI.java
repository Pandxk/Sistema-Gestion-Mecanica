    private void tablaListadoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaListadoMouseClicked
        if (evt.getClickCount() == 2 && formularioPadre != null) {

            int fila = tablaListado.getSelectedRow();
            if (fila >= 0) {
                try {
                    int id = Integer.parseInt(tablaListado.getValueAt(fila, 0).toString());
                    String nombre = tablaListado.getValueAt(fila, 2).toString();
                    int stockMax = Integer.parseInt(tablaListado.getValueAt(fila, 4).toString());

                    String precioStr = tablaListado.getValueAt(fila, 5).toString()
                            .replace("$", "")
                            .replace(",", ".")
                            .trim();
                    double precio = Double.parseDouble(precioStr);

                    String cantStr = JOptionPane.showInputDialog(this,
                            "Producto: " + nombre + "\nStock Disponible: " + stockMax + "\nPrecio: $" + precio + "\n\n¿Cantidad a usar?");

                    if (cantStr != null && !cantStr.isEmpty()) {
                        int cantidad = Integer.parseInt(cantStr);

                        if (cantidad <= 0) {
                            JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a 0");
                            return;
                        }
                        if (cantidad > stockMax) {
                            JOptionPane.showMessageDialog(this, "Stock insuficiente. Máximo: " + stockMax);
                            return;
                        }

                        formularioPadre.recibirProducto(id, nombre, cantidad, precio);

                        javax.swing.SwingUtilities.getWindowAncestor(this).dispose();
                    }
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Error al seleccionar: " + e.getMessage());
                }
            }
        }
    }//GEN-LAST:event_tablaListadoMouseClicked

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tablaListado.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(null, "Seleccione un producto para descartar.");
            return;
        }
        int confirmacion = JOptionPane.showConfirmDialog(null,
                "¿Seguro que desea descartar este producto del inventario?",
                "Descartar Producto", JOptionPane.YES_NO_OPTION);
        if (confirmacion == JOptionPane.YES_OPTION) {
            try {
                int id = Integer.parseInt(tablaListado.getValueAt(fila, 0).toString());
                prodControl.destroy(id);
                ListarProductos();
                JOptionPane.showMessageDialog(null, "Producto eliminado.");
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

