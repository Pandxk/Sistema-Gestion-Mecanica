    private void btn_registrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_registrarActionPerformed
        if (txt_ced.getText().isEmpty() || txt_nom.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "La cédula y el nombre son obligatorios");
            return;
        }
        try {
            cli.setCedula(txt_ced.getText().trim());
            cli.setNombre(capitalizarNombres(txt_nom.getText()));
            cli.setDireccion(capitalizarTexto(txt_dir.getText()));
            cli.setTelefono(txt_telf.getText().trim());
            if (idClienteEdit > 0) {
                cliControl.edit(cli);
                JOptionPane.showMessageDialog(this, "CLIENTE ACTUALIZADO CON ÉXITO");
            } else {
                cliControl.create(cli);
                JOptionPane.showMessageDialog(this, "CLIENTE REGISTRADO CON ÉXITO");
            }
            padre.ListarClientes();
            this.dispose();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "ERROR AL GUARDAR: " + e.getMessage());
        }
    }//GEN-LAST:event_btn_registrarActionPerformed

