    private String capitalizarTexto(String texto) {
        if (texto == null || texto.isEmpty()) {
            return texto;
        }
        texto = texto.trim().toLowerCase();
        return texto.substring(0, 1).toUpperCase() + texto.substring(1);
    }

    private String capitalizarNombres(String texto) {
        if (texto == null || texto.isEmpty()) {
            return texto;
        }
        String[] palabras = texto.trim().toLowerCase().split("\\s+");
        StringBuilder resultado = new StringBuilder();
        for (String palabra : palabras) {
            if (!palabra.isEmpty()) {
                resultado.append(Character.toUpperCase(palabra.charAt(0)));
                resultado.append(palabra.substring(1)).append(" ");
            }
        }
        return resultado.toString().trim();
    }

    private void cargarDatosParaEditar() {
        try {
            cli = cliControl.findCliente(idClienteEdit);
            if (cli != null) {
                txt_ced.setText(cli.getCedula());
                txt_nom.setText(cli.getNombre());
                txt_dir.setText(cli.getDireccion());
                txt_telf.setText(cli.getTelefono());
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "ERROR AL CARGAR LOS DATOS " + e.getMessage());
        }
    }

