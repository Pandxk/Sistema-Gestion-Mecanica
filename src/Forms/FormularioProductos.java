    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        if (txt_cod.getText().isEmpty() || txt_nom.getText().isEmpty()
                || txt_stock.getText().isEmpty() || txt_Precio.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, llene todos los campos obligatorios.");
            return;
        }
        try {
            prod.setCodigo(txt_cod.getText().trim().toUpperCase());
            prod.setNombre(capitalizarTexto(txt_nom.getText()));
            prod.setMarca(capitalizarNombres(txt_marca.getText()));
            try {
                int stock = Integer.parseInt(txt_stock.getText().trim());
                prod.setStock(stock);
                double precio = Double.parseDouble(txt_Precio.getText().replace(",", ".").trim());
                prod.setPrecio(precio);
            } catch (NumberFormatException nfe) {
                JOptionPane.showMessageDialog(this, "Error en números: El Stock debe ser entero y el Precio numérico.");
                return;
            }
            if (idProdEdit > 0) {
                prodControl.edit(prod);
                JOptionPane.showMessageDialog(this, "Producto Actualizado correctamente.");
            } else {
                prodControl.create(prod);
                JOptionPane.showMessageDialog(this, "Producto Agregado al Inventario.");
            }
            padre.ListarProductos();
            padre.seleccionarProductoNuevo(prod.getIdProducto());
            this.dispose();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocurrió un error al guardar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

