    public void ListarVehiculos() {
        model = (DefaultTableModel) tablaListado.getModel();
        model.setRowCount(0);

        List<Vehiculo> lista = vehControl.findVehiculoEntities();
        llenarTabla(lista);
    }

    private void llenarTabla(List<Vehiculo> lista) {
        Object[] ob = new Object[13];
        for (Vehiculo v : lista) {
            ob[0] = v.getIdVehiculo();
            ob[1] = v.getPlaca();
            ob[2] = v.getModelo();
            ob[3] = v.getMarca();
            ob[4] = v.getNumeroChasis();
            ob[5] = v.getNumeroMotor();
            ob[6] = v.getVin();
            ob[7] = v.getColor();
            ob[8] = v.getAnio();
            ob[9] = v.getCilindrada();
            ob[10] = v.getCombustible();
            ob[11] = v.getKilometraje();
            try {
                if (v.getClienteidCliente() != null) {
                    ob[12] = v.getClienteidCliente().getNombre();
                } else {
                    ob[12] = "SIN ASIGNAR";
                }
            } catch (Exception e) {
                ob[12] = "ERROR";
            }

            model.addRow(ob);
        }
        tablaListado.setModel(model);
    }

