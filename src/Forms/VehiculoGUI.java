    private void abrirFormulario(int id) {
        JFrame framePadre = (JFrame) SwingUtilities.getWindowAncestor(this);

        // Efecto Cine (GlassPane)
        JPanel fondoOscuro = new JPanel() {
            @Override
            protected void paintComponent(Graphics g) {
                g.setColor(new Color(0, 0, 0, 150));
                g.fillRect(0, 0, getWidth(), getHeight());
            }
        };
        fondoOscuro.setOpaque(false);
        framePadre.setGlassPane(fondoOscuro);
        fondoOscuro.setVisible(true);
        Forms.FormularioVehiculo ventana = new Forms.FormularioVehiculo(framePadre, true, this, id);
        ventana.setVisible(true);

        // Quitar Efecto
        fondoOscuro.setVisible(false);
    }
    private void btn_elim1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_elim1ActionPerformed
        int fila = tablaListado.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(null, "SELECCIONE UN VEHICULO PARA ELIMINAR");
            return;
        }
        int confirmacion = JOptionPane.showConfirmDialog(null, "ESTA SEGURO?", "ELIMINAR ", JOptionPane.YES_NO_OPTION);
        if (confirmacion == JOptionPane.YES_OPTION) {
            try {
                int id = Integer.parseInt(tablaListado.getValueAt(fila, 0).toString());
                vehControl.destroy(id);
                ListarVehiculos();
                JOptionPane.showMessageDialog(null, "VEHICULO ELIMINADO");
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "ERROR" + e.getMessage());
            }
        }
    }//GEN-LAST:event_btn_elim1ActionPerformed

    private void btn_buscar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_buscar1ActionPerformed
        String texto = txt_buscar.getText().trim().toUpperCase();
        int criterio = cbx_criterio.getSelectedIndex(); // 0=Seleccione, 1=Placa, 2=Marca

        if (criterio == 0) {
            JOptionPane.showMessageDialog(null, "Por favor, seleccione buscar por PLACA o MARCA.");
            return;
        }
        if (texto.isEmpty()) {
            ListarVehiculos();
            return;
        }

        model.setRowCount(0);
        List<Vehiculo> lista = vehControl.findVehiculoEntities();
        for (int i = 0; i < lista.size(); i++) {
            Vehiculo v = lista.get(i);
            boolean coincide = false;

            if (criterio == 1) {
                if (v.getPlaca() != null && v.getPlaca().contains(texto)) {
                    coincide = true;
                }
            } else if (criterio == 2) {
                if (v.getMarca() != null && v.getMarca().toUpperCase().contains(texto)) {
                    coincide = true;
                }
            }
            if (!coincide) {
                lista.remove(i);
                i--;
            }
        }
        if (lista.isEmpty()) {
            JOptionPane.showMessageDialog(null, "No se ha encontrado el vehículo solicitado.");
            ListarVehiculos();
            txt_buscar.setText("");
        } else {
            llenarTabla(lista);
        }
    }//GEN-LAST:event_btn_buscar1ActionPerformed

