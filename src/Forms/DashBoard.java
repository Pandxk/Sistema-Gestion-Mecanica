    private void cargarKPI(Date inicio, Date fin) {
        try (Connection cn = DriverManager.getConnection("jdbc:mysql://localhost:3306/bdmecanica?serverTimezone=UTC", "root", "Jose maldonado18"); CallableStatement cs = cn.prepareCall("{call sp_ObtenerTotalVentas(?, ?)}")) {

            cs.setDate(1, inicio);
            cs.setDate(2, fin);
            ResultSet rs = cs.executeQuery();

            if (rs.next()) {
                double total = rs.getDouble("Total");
                lblTotalVendido.setText(String.format("$ %.2f", total));
            }
        } catch (Exception e) {
            System.out.println("Error KPI: " + e.getMessage());
        }
    }

    private void graficarBarras(Date inicio, Date fin) {
        DefaultCategoryDataset datos = new DefaultCategoryDataset();
        try (Connection cn = DriverManager.getConnection("jdbc:mysql://localhost:3306/bdmecanica?serverTimezone=UTC", "root", "Jose maldonado18"); CallableStatement cs = cn.prepareCall("{call sp_VentasPorDia(?, ?)}")) {
            cs.setDate(1, inicio);
            cs.setDate(2, fin);
            ResultSet rs = cs.executeQuery();
            while (rs.next()) {
                String dia = rs.getString("Dia");
                double monto = rs.getDouble("TotalVendido");
                datos.addValue(monto, "Ventas", dia);
            }
            JFreeChart grafico = ChartFactory.createBarChart(
                    "Ventas por Día",
                    "Día",
                    "Dinero ($)",
                    datos,
                    PlotOrientation.VERTICAL,
                    false, true, false);
            org.jfree.chart.plot.CategoryPlot plot = grafico.getCategoryPlot();
            org.jfree.chart.renderer.category.BarRenderer renderer = (org.jfree.chart.renderer.category.BarRenderer) plot.getRenderer();
            renderer.setMaximumBarWidth(0.1);
            ChartPanel panel = new ChartPanel(grafico);
            panel.setMouseWheelEnabled(true);
            pnlBarras.setLayout(new java.awt.BorderLayout());
            pnlBarras.add(panel, BorderLayout.CENTER);
            pnlBarras.validate();
        } catch (Exception e) {
            System.out.println("Error Barras: " + e.getMessage());
        }
    }

    private void graficarPastel(Date inicio, Date fin) {
        DefaultPieDataset datos = new DefaultPieDataset();
        try (Connection cn = DriverManager.getConnection("jdbc:mysql://localhost:3306/bdmecanica?serverTimezone=UTC", "root", "Jose maldonado18"); CallableStatement cs = cn.prepareCall("{call sp_TopProductos(?, ?)}")) {
            cs.setDate(1, inicio);
            cs.setDate(2, fin);
            ResultSet rs = cs.executeQuery();
            while (rs.next()) {
                String prod = rs.getString("Producto");
                int cant = rs.getInt("CantidadTotal");
                datos.setValue(prod + " (" + cant + ")", cant);
            }
            JFreeChart grafico = ChartFactory.createPieChart(
                    "Top 5 Repuestos",
                    datos,
                    true, true, false);
            ChartPanel panel = new ChartPanel(grafico);
            panel.setMouseWheelEnabled(true);
            pnlPastel.removeAll();
            pnlPastel.setLayout(new java.awt.BorderLayout());
            pnlPastel.add(panel, BorderLayout.CENTER);
            pnlPastel.validate();
        } catch (Exception e) {
            System.out.println("Error Pastel: " + e.getMessage());
        }
    }
