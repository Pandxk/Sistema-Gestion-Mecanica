    private void btnFiltrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFiltrarActionPerformed
        java.time.LocalDate fechaLocalInicio = dpInicio.getDate();
        java.time.LocalDate fechaLocalFin = dpFin.getDate();
        java.time.LocalDate hoy = java.time.LocalDate.now();
        if (fechaLocalInicio == null || fechaLocalFin == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "️ Error: Debes seleccionar ambas fechas (Desde y Hasta).",
                    "Faltan Datos", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (fechaLocalInicio.isAfter(fechaLocalFin)) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "️ Error de Lógica: La fecha de 'Inicio' no puede ser posterior a la fecha 'Fin'.\n"
                    + "Por favor corrige el rango de fechas.",
                    "Rango Incorrecto", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (fechaLocalInicio.isAfter(hoy)) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "️ Error: No puedes consultar fechas futuras.\n"
                    + "Hoy es: " + hoy,
                    "Fecha Futura", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            java.sql.Date sqlInicio = java.sql.Date.valueOf(fechaLocalInicio);
            java.sql.Date sqlFin = java.sql.Date.valueOf(fechaLocalFin);
            System.out.println("Filtrando reporte: " + sqlInicio + " al " + sqlFin);
            cargarKPI(sqlInicio, sqlFin);
            graficarBarras(sqlInicio, sqlFin);
            graficarPastel(sqlInicio, sqlFin);
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al generar reporte: " + e.getMessage());
        }
    }//GEN-LAST:event_btnFiltrarActionPerformed

