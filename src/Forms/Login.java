    public void validar() {
        String correo = txt_Correo.getText();
        String pass = String.valueOf(txt_pass.getPassword());

        // Verifico que no esten vacios
        if (!"".equals(correo) && !"".equals(pass)) {
            // Busco el usuario en la BD usando el método especial del controlador
            u = usuControl.validarUsuario(correo, pass);
            if (u != null) {
                // Si existe, abro el sistema
                try {
                    Forms.Sistema sis = new Forms.Sistema();
                    sis.setVisible(true);
                    this.dispose(); // Cierro el Login
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(null, "Error al cargar el Sistema: " + e);
                }
            } else {
                JOptionPane.showMessageDialog(null, "Correo o Contraseña incorrectos");
            }
        } else {
            JOptionPane.showMessageDialog(null, "Por favor ingrese sus datos");
        }
    }

