    private String capitalizarNombres(String texto) {
        if (texto == null || texto.isEmpty()) {
            return texto;
        }
        String[] palabras = texto.trim().toLowerCase().split("\\s+");
        StringBuilder resultado = new StringBuilder();
        for (String palabra : palabras) {
            if (!palabra.isEmpty()) {
                resultado.append(Character.toUpperCase(palabra.charAt(0)));
                resultado.append(palabra.substring(1)).append(" ");
            }
        }
        return resultado.toString().trim();
    }
    private void cargarComboClientes() {
        cbx_cliente.removeAllItems();
        List<Cliente> clientes = cliControl.findClienteEntities();
        for (Cliente c : clientes) {
            cbx_cliente.addItem(c);
        }
    }
    private void cargarDatos() {
        veh = vehControl.findVehiculo(idVehiculoEdit);
        if (veh != null) {
            txt_placa.setText(veh.getPlaca());
            txt_modelo.setText(veh.getModelo());
            txt_marca.setText(veh.getMarca());
            txt_chasis.setText(veh.getNumeroChasis());
            txt_motor.setText(veh.getNumeroMotor());
            txt_vin.setText(veh.getVin());
            txt_color.setText(veh.getColor());
            txt_anio.setText(veh.getAnio());
            txt_cilin.setText(veh.getCilindrada());
            txt_comb.setText(veh.getCombustible());
            txt_kil.setText(veh.getKilometraje());
            if (veh.getClienteidCliente() != null) {
                int idDueño = veh.getClienteidCliente().getIdCliente();
                for (int i = 0; i < cbx_cliente.getItemCount(); i++) {
                    Object item = cbx_cliente.getItemAt(i);
                    if (item instanceof Cliente) {
                        Cliente c = (Cliente) item;

                        if (c.getIdCliente() == idDueño) {
                            cbx_cliente.setSelectedIndex(i);
                            break;
                        }
                    }
                }
            }
        }
    }

