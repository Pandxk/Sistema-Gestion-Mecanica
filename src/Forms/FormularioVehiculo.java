    private void btn_RegActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_RegActionPerformed
        if (txt_placa.getText().isEmpty() || txt_marca.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "PLACA Y MARCA SON OBLIGATORIOS");
            return;
        }

        try {
            veh.setPlaca(txt_placa.getText().trim().toUpperCase());
            veh.setNumeroChasis(txt_chasis.getText().trim().toUpperCase());
            veh.setNumeroMotor(txt_motor.getText().trim().toUpperCase());
            veh.setVin(txt_vin.getText().trim().toUpperCase());
            veh.setMarca(capitalizarNombres(txt_marca.getText()));
            veh.setModelo(capitalizarNombres(txt_modelo.getText()));
            veh.setColor(capitalizarNombres(txt_color.getText()));
            veh.setCombustible(capitalizarNombres(txt_comb.getText()));
            veh.setAnio(txt_anio.getText().trim());
            veh.setCilindrada(txt_cilin.getText().trim());
            veh.setKilometraje(txt_kil.getText().trim());
            Cliente clienteSeleccionado = (Cliente) cbx_cliente.getSelectedItem();
            veh.setClienteidCliente(clienteSeleccionado);
            if (idVehiculoEdit > 0) {
                vehControl.edit(veh);
                JOptionPane.showMessageDialog(this, "VEHICULO ACTUALIZADO");
            } else {
                vehControl.create(veh);
                JOptionPane.showMessageDialog(this, "VEHICULO REGISTRADO CORRECTAMENTE");
            }
            padre.ListarVehiculos();
            this.dispose();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "ERROR: " + e.getMessage());
        }
    }//GEN-LAST:event_btn_RegActionPerformed

