    private void abrirReporte(String nombreArchivo) {
        javax.swing.JPanel fondoOscuro = new javax.swing.JPanel() {
            @Override
            protected void paintComponent(java.awt.Graphics g) {
                g.setColor(new java.awt.Color(0, 0, 0, 150)); 
                g.fillRect(0, 0, getWidth(), getHeight());
            }
        };
        fondoOscuro.setOpaque(false);
        this.setGlassPane(fondoOscuro);
        fondoOscuro.setVisible(true);
        try {
            java.sql.Connection cn = java.sql.DriverManager.getConnection(
                    "jdbc:mysql://localhost:3306/bdmecanica?serverTimezone=UTC",
                    "root", "Jose maldonado18");

            String ruta = "src/reportes/" + nombreArchivo;
            java.io.File archivo = new java.io.File(ruta);

            if (!archivo.exists()) {
                fondoOscuro.setVisible(false);
                JOptionPane.showMessageDialog(this, "No encuentro el archivo: " + ruta, "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            net.sf.jasperreports.engine.JasperPrint informe = net.sf.jasperreports.engine.JasperFillManager.fillReport(ruta, null, cn);
            javax.swing.JDialog visorDialog = new javax.swing.JDialog(this, "Vista Previa - " + nombreArchivo, true);
            visorDialog.setSize(1000, 700);
            visorDialog.setLocationRelativeTo(null);
            net.sf.jasperreports.view.JRViewer panelVisor = new net.sf.jasperreports.view.JRViewer(informe);
            visorDialog.add(panelVisor);
            visorDialog.setVisible(true);
            fondoOscuro.setVisible(false);
        } catch (Exception e) {
            fondoOscuro.setVisible(false);
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error al generar reporte: " + e.getMessage());
        }
    }
    private void personalizarBoton(javax.swing.JButton boton, java.awt.Color colorNormal, java.awt.Color colorHover) {
        boton.setBackground(colorNormal);
        boton.setForeground(java.awt.Color.WHITE); 
        boton.setFocusPainted(false); 
        boton.setBorderPainted(false); 
        boton.setOpaque(true); 
        boton.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseEntered(java.awt.event.MouseEvent evt) {
                boton.setBackground(colorHover);
                boton.setCursor(new java.awt.Cursor(java.awt.Cursor.HAND_CURSOR));
            }

            @Override
            public void mouseExited(java.awt.event.MouseEvent evt) {
                boton.setBackground(colorNormal);
            }
        });
    }

