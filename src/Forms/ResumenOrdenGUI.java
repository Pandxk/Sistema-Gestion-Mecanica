    public void cargarDatosResumen(Servicio servicio, java.util.List<ServicioGUI.RepuestoUso> listaRepuestos, double manoObra) {
        try {
            String nombreCliente = servicio.getVehiculoidVehiculo().getClienteidCliente().getNombre();
            txtCliente.setText(nombreCliente);
        } catch (Exception e) {
            txtCliente.setText("Consumidor Final");
        }

        txtVehiculo.setText(servicio.getVehiculoidVehiculo().getPlaca() + " - " + servicio.getVehiculoidVehiculo().getModelo());
        txtNroOrden.setText(String.valueOf(servicio.getIdServicio()));
        txtFecha.setText(java.time.LocalDate.now().toString());
        javax.swing.table.DefaultTableModel modeloTabla = (javax.swing.table.DefaultTableModel) tablaResumen.getModel();
        modeloTabla.setRowCount(0); 
        for (ServicioGUI.RepuestoUso r : listaRepuestos) {
            modeloTabla.addRow(new Object[]{
                r.cantidad,
                r.nombre,
                String.format("%.2f", r.precioUnitario),
                String.format("%.2f", r.subtotal)
            });
        }
        if (manoObra > 0) {
            modeloTabla.addRow(new Object[]{
                "1",
                "Servicio de Mano de Obra",
                String.format("%.2f", manoObra),
                String.format("%.2f", manoObra)
            });
        }
        txtTotalPagar.setText(String.format("$ %.2f", servicio.getCosto()));
    }

